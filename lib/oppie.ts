export function oppieGreet(name: string): string {
  const n = name.trim().slice(0, 24);
  if (n === "") return "oh good, another stray. I'm OPPIE, resident intelligence. ask me anything. I'll answer anyway.";
  return "oh good, " + n + ". I'm OPPIE, resident intelligence. ask me anything. I'll answer anyway.";
}

export function pick(arr: string[]): string {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function shuffle(arr: string[]): string[] {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const t = a[i];
    a[i] = a[j];
    a[j] = t;
  }
  return a;
}

export function cap(s: string, n: number): string {
  return s.length > n ? s.slice(0, n) : s;
}
