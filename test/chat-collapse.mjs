import { chromium } from "playwright";
const BASE = process.argv[2] || "http://localhost:3123";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const browser = await chromium.launch();
const ctx = await browser.newContext({ permissions: ["clipboard-read", "clipboard-write"] });
const A = await ctx.newPage();
const B = await ctx.newPage();
const res = [];
const mark = (n, ok, d) => { console.log((ok ? "PASS " : "FAIL ") + n + (d ? " — " + d : "")); res.push(ok); };
const errs = [];
A.on("pageerror", (e) => errs.push("A:" + String(e.message).slice(0, 100)));
B.on("pageerror", (e) => errs.push("B:" + String(e.message).slice(0, 100)));
A.on("console", (m) => { if (m.type() === "error") errs.push("A console: " + m.text().slice(0, 100)); });
const openChat = async (pg) => {
  await pg.evaluate(() => {
    const x = Array.from(document.querySelectorAll("button")).find((q) => ((q.textContent || "").trim().toLowerCase() === "victims' chat"));
    if (x) x.click();
  });
  await pg.waitForSelector('input[placeholder="ask anything..."]', { timeout: 10000 });
};
await B.goto(BASE, { waitUntil: "domcontentloaded" });
await A.goto(BASE, { waitUntil: "domcontentloaded" });
await sleep(5000);
await openChat(A);
await A.getByRole("button", { name: "collapse chat" }).click();
await sleep(800);
mark("collapse-folds", await A.evaluate(() => !!document.querySelector(".chat-fold.folded")), "header-only");
await openChat(B);
const probe = "collapse-probe-" + Math.floor(Math.random() * 1e6);
await B.locator('input[placeholder="ask anything..."]').fill(probe);
await B.keyboard.press("Enter");
try { await A.waitForFunction((t) => document.body.innerText.includes(t), "1 NEW", { timeout: 15000 }); } catch (e) {}
mark("unread-badge", await A.evaluate(() => document.body.innerText.includes("1 NEW")), "1 NEW shown");
await A.screenshot({ path: "test/screenshots/chat-fix/collapsed-unread-1440.png" });
await A.getByRole("button", { name: "collapse chat" }).click();
await sleep(800);
const cleared = await A.evaluate(() => !document.body.innerText.includes(" NEW"));
const seen = await A.evaluate((t) => document.body.innerText.includes(t), probe);
mark("expand-clears", cleared && seen, "badge gone, msg visible, history intact");
await A.screenshot({ path: "test/screenshots/chat-fix/expanded-1440.png" });
await A.setViewportSize({ width: 390, height: 844 });
await sleep(600);
await A.getByRole("button", { name: "collapse chat" }).click();
await sleep(600);
const probe2 = "collapse-probe2-" + Math.floor(Math.random() * 1e6);
await B.locator('input[placeholder="ask anything..."]').fill(probe2);
await B.keyboard.press("Enter");
try { await A.waitForFunction((t) => document.body.innerText.includes(t), "1 NEW", { timeout: 15000 }); } catch (e) {}
mark("unread-badge-390", await A.evaluate(() => document.body.innerText.includes("1 NEW")), "mobile badge");
await A.screenshot({ path: "test/screenshots/chat-fix/collapsed-unread-390.png" });
await A.getByRole("button", { name: "collapse chat" }).click();
await sleep(600);
await A.screenshot({ path: "test/screenshots/chat-fix/expanded-390.png" });
await A.getByRole("button", { name: "collapse chat" }).click();
await sleep(500);
await A.reload({ waitUntil: "domcontentloaded" });
await sleep(5000);
const stored = await A.evaluate(() => { try { return localStorage.getItem("opp_chat_collapsed"); } catch (e) { return null; } });
await openChat(A);
await sleep(600);
mark("persist-reload", stored === "1" && await A.evaluate(() => !!document.querySelector(".chat-fold.folded")), "stored=" + stored);
console.log("errors: " + JSON.stringify(errs));
await browser.close();
console.log("chat-collapse-done " + res.filter(Boolean).length + "/" + res.length);
